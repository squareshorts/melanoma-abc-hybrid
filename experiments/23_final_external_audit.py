"""Current external audit for the lesion-aware manuscript (v2 series).

Primary safeguards:
- operating thresholds are selected from HAM10000 validation predictions only;
- BCN20000 outcomes never select primary thresholds;
- external confidence intervals resample lesion_id clusters;
- lesion-mean analyses give each BCN20000 lesion one prediction.

The script expects prediction files generated by the training/evaluation pipeline and
BCN20000 metadata under config.yaml:data_root. It writes tables to results/final/.
"""
from __future__ import annotations

import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "final"
OUT.mkdir(parents=True, exist_ok=True)
SEED = 42
N_BOOT = 5000
MODELS = ["Handcrafted", "Deep", "Hybrid"]
PRED_PATHS = {
    "Handcrafted": ROOT / "results/runs/handcrafted/bcn20000_predictions_handcrafted.csv",
    "Deep": ROOT / "results/runs/deep_baseline/bcn20000_predictions_deep.csv",
    "Hybrid": ROOT / "results/runs/hybrid/bcn20000_predictions_hybrid.csv",
}
VAL_PATH = OUT / "source_validation_predictions_all_models.csv"


def load_config() -> dict:
    import yaml
    with open(ROOT / "config.yaml", "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def build_validation_predictions(cfg: dict) -> pd.DataFrame:
    if VAL_PATH.exists():
        return pd.read_csv(VAL_PATH)

    data_root = Path(cfg["data_root"])
    meta = pd.read_csv(data_root / "HAM10000" / "metadata.csv")
    if "label" not in meta.columns:
        meta["label"] = (meta["dx"].astype(str) == "mel").astype(int)

    with open(ROOT / cfg["derived"]["split_json"], "r", encoding="utf-8") as f:
        split = json.load(f)
    val_ids = set(split["val"])
    val = meta[meta["lesion_id"].astype(str).isin(val_ids)][
        ["image_id", "lesion_id", "label"]
    ].copy()
    val = val.rename(columns={"label": "y_true"})

    deep_path = ROOT / "results/runs/deep_baseline/ham_val_predictions_deep.csv"
    if not deep_path.exists():
        raise FileNotFoundError(f"Missing deep validation predictions: {deep_path}")
    deep = pd.read_csv(deep_path)[["image_id", "y_prob"]].rename(columns={"y_prob": "Deep"})
    val = val.merge(deep, on="image_id", how="inner")

    feats = pd.read_csv(ROOT / cfg["derived"]["ham_abc_csv"])
    val = val.merge(feats, on="image_id", how="inner")

    hp = joblib.load(ROOT / "results/runs/handcrafted/handcrafted_xgb.joblib")
    hmodel = hp["model"] if isinstance(hp, dict) else hp
    hcols = hp.get("feat_cols") if isinstance(hp, dict) else [
        c for c in feats.columns if c.startswith(("A_", "B_", "C_"))
    ]
    val["Handcrafted"] = hmodel.predict_proba(val[hcols].to_numpy())[:, 1]

    emb = np.load(ROOT / cfg["derived"]["ham_emb_npy"])
    emb_ids = pd.read_csv(ROOT / cfg["derived"]["ham_emb_ids"])["image_id"].astype(str).tolist()
    emap = {k: i for i, k in enumerate(emb_ids)}
    val = val[val["image_id"].astype(str).isin(emap)].reset_index(drop=True)
    e = emb[[emap[str(i)] for i in val["image_id"]]]

    hp = joblib.load(ROOT / "results/runs/hybrid/hybrid_xgb.joblib")
    model = hp["model"] if isinstance(hp, dict) else hp
    fcols = hp.get("feat_cols") if isinstance(hp, dict) else hcols
    x = np.concatenate([val[fcols].to_numpy(), e], axis=1)
    val["Hybrid"] = model.predict_proba(x)[:, 1]

    keep = ["image_id", "lesion_id", "y_true", "Handcrafted", "Deep", "Hybrid"]
    val[keep].to_csv(VAL_PATH, index=False)
    return val[keep]


def metric(y: np.ndarray, p: np.ndarray, name: str) -> float:
    if name == "AUC":
        return float(roc_auc_score(y, p))
    if name == "AP":
        return float(average_precision_score(y, p))
    if name == "Brier":
        return float(brier_score_loss(y, p))
    raise ValueError(name)


def cluster_bootstrap(df: pd.DataFrame, prob: str, name: str, n_boot=N_BOOT, seed=SEED):
    rng = np.random.default_rng(seed)
    lesions = df["lesion_id"].astype(str).unique()
    groups = {k: v for k, v in df.groupby(df["lesion_id"].astype(str), sort=False)}
    vals = []
    for _ in range(n_boot):
        sampled = rng.choice(lesions, size=len(lesions), replace=True)
        b = pd.concat([groups[k] for k in sampled], ignore_index=True)
        y = b["y_true"].to_numpy(int)
        p = b[prob].to_numpy(float)
        if name in ("AUC", "AP") and np.unique(y).size < 2:
            continue
        vals.append(metric(y, p, name))
    a = np.asarray(vals, float)
    return float(np.quantile(a, 0.025)), float(np.quantile(a, 0.975))


def merge_external(cfg: dict) -> pd.DataFrame:
    meta_path = Path(cfg["data_root"]) / cfg["raw"]["bcn20000"]["metadata"]
    meta = pd.read_csv(meta_path).rename(columns={"isic_id": "image_id"})
    out = None
    for model, path in PRED_PATHS.items():
        if not path.exists():
            raise FileNotFoundError(f"Missing prediction file: {path}")
        d = pd.read_csv(path)[["image_id", "y_true", "y_prob"]].rename(
            columns={"y_prob": model}
        )
        out = d if out is None else out.merge(d[["image_id", model]], on="image_id", how="inner")
    out = out.merge(meta, on="image_id", how="left", validate="many_to_one")
    if out["lesion_id"].isna().any():
        raise ValueError("Evaluated BCN20000 images are missing lesion_id")
    return out


def external_performance(df: pd.DataFrame):
    rows = []
    for model in MODELS:
        y = df["y_true"].to_numpy(int)
        p = df[model].to_numpy(float)
        row = {"model": model, "N_images": len(df), "N_lesions": df.lesion_id.nunique()}
        for name in ("AUC", "AP", "Brier"):
            point = metric(y, p, name)
            lo, hi = cluster_bootstrap(df, model, name)
            row.update({name: point, f"{name}_ci_low": lo, f"{name}_ci_high": hi})
        rows.append(row)
    pd.DataFrame(rows).to_csv(OUT / "table_external_performance_clustered.csv", index=False)


def lesion_mean_performance(df: pd.DataFrame):
    d = df.groupby("lesion_id", as_index=False).agg(
        {"y_true": "max", **{m: "mean" for m in MODELS}}
    )
    rows = []
    for model in MODELS:
        y, p = d.y_true.to_numpy(int), d[model].to_numpy(float)
        rows.append({
            "model": model,
            "N_lesions": len(d),
            "AUC": metric(y, p, "AUC"),
            "AP": metric(y, p, "AP"),
            "Brier": metric(y, p, "Brier"),
        })
    pd.DataFrame(rows).to_csv(OUT / "table_external_performance_lesion_mean.csv", index=False)
    return d


def threshold_at_specificity(y, p, target_spec: float):
    y = np.asarray(y, int)
    p = np.asarray(p, float)
    best = None
    for t in np.unique(p)[::-1]:
        pred = p >= t
        neg = y == 0
        pos = y == 1
        spec = float(np.mean(~pred[neg]))
        sens = float(np.mean(pred[pos]))
        if spec >= target_spec and (
            best is None or sens > best[1] or (sens == best[1] and t < best[0])
        ):
            best = (float(t), sens, spec)
    return best if best is not None else (float("inf"), 0.0, 1.0)


def apply_thresholds(df: pd.DataFrame, lesion_mean: pd.DataFrame):
    val = build_validation_predictions(load_config())
    targets = [0.80, 0.90, 0.95]
    rows = []
    lesion_rows = []

    for model in MODELS:
        for target in targets:
            thr, src_sens, src_spec = threshold_at_specificity(
                val.y_true, val[model], target
            )
            pred = df[model].to_numpy(float) >= thr
            y = df.y_true.to_numpy(int)
            rows.append({
                "model": model,
                "target_source_specificity": target,
                "threshold": thr,
                "source_sensitivity": src_sens,
                "source_specificity": src_spec,
                "external_sensitivity": float(pred[y == 1].mean()),
                "external_specificity": float((~pred[y == 0]).mean()),
            })
    pd.DataFrame(rows).to_csv(OUT / "table_frozen_source_operating_points.csv", index=False)

    val_les = val.groupby("lesion_id", as_index=False).agg(
        y_true=("y_true", "max"),
        **{m: (m, "mean") for m in MODELS},
    )
    for model in MODELS:
        for target in targets:
            thr, src_sens, src_spec = threshold_at_specificity(
                val_les.y_true, val_les[model], target
            )
            pred = lesion_mean[model].to_numpy(float) >= thr
            y = lesion_mean.y_true.to_numpy(int)
            lesion_rows.append({
                "model": model,
                "target_source_specificity": target,
                "threshold": thr,
                "source_sensitivity": src_sens,
                "source_specificity": src_spec,
                "external_sensitivity": float(pred[y == 1].mean()),
                "external_specificity": float((~pred[y == 0]).mean()),
            })
    pd.DataFrame(lesion_rows).to_csv(
        OUT / "table_frozen_operating_points_lesion_mean.csv", index=False
    )


def write_unit_summary(df: pd.DataFrame):
    counts = df.groupby("lesion_id").size()
    pd.DataFrame([{
        "N_images": len(df),
        "N_lesions": int(counts.size),
        "median_images_per_lesion": float(counts.median()),
        "max_images_per_lesion": int(counts.max()),
        "fraction_lesions_with_multiple_images": float((counts > 1).mean()),
    }]).to_csv(OUT / "table_external_unit_of_analysis.csv", index=False)


def main():
    cfg = load_config()
    df = merge_external(cfg)
    write_unit_summary(df)
    external_performance(df)
    lesion_df = lesion_mean_performance(df)
    apply_thresholds(df, lesion_df)
    print(f"Wrote current primary external audit tables to {OUT}")
    print(f"BCN20000 evaluated set: {len(df):,} images from {df.lesion_id.nunique():,} lesions")


if __name__ == "__main__":
    main()
